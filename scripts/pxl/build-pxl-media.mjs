/**
 * PXL — reference imagery to web media.
 *
 *   node scripts/pxl/build-pxl-media.mjs
 *
 * The other asset script, `scripts/build-assets.mjs`, pulls the Duna 6.1
 * photography from dunahajok.hu. The PXL is a new product and there is no
 * photography: what exists is the design studio's own renders, delivered as
 * local files, so they get their own small pipeline rather than a remote
 * fetch bolted onto the other one.
 *
 * These are *design renders*, not photographs, and the grading here is
 * deliberately almost nothing — a render is already a controlled image and
 * pushing saturation into one only makes it look retouched.
 *
 * The `pxl-hero-side` derivative has one job beyond documentation: it is what
 * the WebGL scene shows if the GLB fails to load. Section 34 of the phase
 * brief is explicit that the fallback must be specific to the PXL, and an
 * empty river or a spinner is not.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const SOURCE = path.join(ROOT, "assets", "source", "pxl");
const OUT = path.join(ROOT, "public", "media", "pxl");
const MANIFEST = path.join(ROOT, "src", "lib", "pxl.media.generated.ts");

/**
 * `crop` removes fractions of each edge: [left, top, right, bottom]. The
 * colour studies are A4 sheets with two stacked renders and a white margin,
 * so each usable image is a crop out of one.
 */
const ASSETS = [
  {
    id: "pxl-hero-side",
    file: "pxl-side-20240719.jpg",
    alt: "The Duna PXL in profile, bow to the right, in the design studio's own render.",
    crop: [0.11, 0.22, 0.06, 0.24],
    maxWidth: 2000,
  },
  {
    id: "pxl-views",
    file: "pxl-views-20240815c.jpg",
    alt: "Three studies of the Duna PXL: profile, cockpit from above, and stern quarter.",
    maxWidth: 2000,
  },
  {
    id: "pxl-water-white",
    file: "pxl-colours-01.jpg",
    alt: "The Duna PXL on open water with a white hull.",
    crop: [0.085, 0.03, 0.08, 0.52],
    maxWidth: 1800,
  },
  {
    id: "pxl-water-sage",
    file: "pxl-colours-01.jpg",
    alt: "The Duna PXL on open water with a sage-green hull.",
    crop: [0.085, 0.51, 0.08, 0.04],
    maxWidth: 1800,
  },
  {
    id: "pxl-water-black",
    file: "pxl-colours-02.jpg",
    alt: "The Duna PXL on open water with a black hull.",
    crop: [0.085, 0.03, 0.08, 0.52],
    maxWidth: 1800,
  },
  {
    id: "pxl-water-warm-grey",
    file: "pxl-colours-03.jpg",
    alt: "The Duna PXL on open water with a warm grey hull.",
    crop: [0.085, 0.03, 0.08, 0.52],
    maxWidth: 1800,
  },
  {
    id: "pxl-water-gold",
    file: "pxl-colours-04.jpg",
    alt: "The Duna PXL on open water with a gold hull.",
    crop: [0.085, 0.03, 0.08, 0.52],
    maxWidth: 1800,
  },
  {
    id: "pxl-water-navy",
    file: "pxl-colours-04.jpg",
    alt: "The Duna PXL on open water with a navy hull.",
    crop: [0.085, 0.51, 0.08, 0.04],
    maxWidth: 1800,
  },
];

await mkdir(OUT, { recursive: true });
const entries = [];

for (const asset of ASSETS) {
  const input = sharp(path.join(SOURCE, asset.file));
  const meta = await input.metadata();

  let pipeline = input;
  if (asset.crop) {
    const [l, t, r, b] = asset.crop;
    pipeline = pipeline.extract({
      left: Math.round(meta.width * l),
      top: Math.round(meta.height * t),
      width: Math.round(meta.width * (1 - l - r)),
      height: Math.round(meta.height * (1 - t - b)),
    });
  }
  pipeline = pipeline.resize({
    width: asset.maxWidth,
    withoutEnlargement: true,
    fit: "inside",
  });

  const buffer = await pipeline.webp({ quality: 88, effort: 6 }).toBuffer();
  const out = path.join(OUT, `${asset.id}.webp`);
  await writeFile(out, buffer);
  const { width, height } = await sharp(buffer).metadata();

  const blur = await sharp(buffer)
    .resize({ width: 20 })
    .webp({ quality: 32 })
    .toBuffer();

  entries.push({
    id: asset.id,
    src: `/media/pxl/${asset.id}.webp`,
    width,
    height,
    alt: asset.alt,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    source: `assets/source/pxl/${asset.file}`,
  });
  console.log(`  ${asset.id.padEnd(22)}${width}×${height}  ${(buffer.length / 1024).toFixed(0)} kB`);
}

const body = entries
  .map((e) => `  "${e.id}": {
    id: "${e.id}",
    src: "${e.src}",
    width: ${e.width},
    height: ${e.height},
    alt: ${JSON.stringify(e.alt)},
    blurDataURL: "${e.blurDataURL}",
    source: "${e.source}",
  },`)
  .join("\n");

await writeFile(MANIFEST, `// GENERATED by scripts/pxl/build-pxl-media.mjs — do not edit by hand.
// Run \`npm run pxl\` to regenerate.
//
// Duna PXL design renders. These are the studio's own images, not photography:
// the boat is new and has not been shot. Treat them as the reference for what
// the real-time model has to look like, and as the fallback the WebGL scene
// falls back *to*.

export interface PxlMediaAsset {
  readonly id: string;
  readonly src: string;
  readonly width: number;
  readonly height: number;
  readonly alt: string;
  readonly blurDataURL: string;
  /** The delivered file this was derived from. */
  readonly source: string;
}

export const PXL_MEDIA = {
${body}
} as const satisfies Record<string, PxlMediaAsset>;

export type PxlMediaId = keyof typeof PXL_MEDIA;
`);

console.log(`\n  wrote ${path.relative(ROOT, MANIFEST)} (${entries.length} assets)`);
